"""Hotstrings and hotkeys: read hotstrings.json, render an AutoHotkey v2 script, run it."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

from . import procs

NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)
MODIFIERS = {"#": "Win", "^": "Ctrl", "!": "Alt", "+": "Shift"}


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def fill(text: str, owner: str) -> str:
    return text.replace("{me}", owner)


def key_label(keys: str) -> str:
    """'#b' -> 'Win+B', '^!{F13}' -> 'Ctrl+Alt+F13', 'CapsLock' -> 'CapsLock'."""
    parts = []
    rest = keys
    while rest and rest[0] in MODIFIERS and len(rest) > 1:
        parts.append(MODIFIERS[rest[0]])
        rest = rest[1:]
    rest = rest.strip("{}")
    parts.append(rest.upper() if len(rest) == 1 else rest)
    return "+".join(parts)


def text_preview(text: str) -> str:
    """How a text hotstring reads on the card: newlines shown as the return symbol."""
    return text.replace("\n", " ↵ ").strip()


def _send_escape(text: str) -> str:
    """Plain text to hotstring replacement syntax: special keys braced, newlines as {Enter}."""
    out = []
    for char in text:
        if char in "!^+#{}":
            out.append("{" + char + "}")
        elif char == "\n":
            out.append("{Enter}")
        else:
            out.append(char)
    # A semicolon after whitespace would start a comment in the script.
    return "".join(out).replace(" ;", " `;")


def _string(text: str) -> str:
    """An AutoHotkey v2 double-quoted string literal."""
    escaped = text.replace("`", "``").replace('"', '`"').replace("\n", "`n").replace("\r", "")
    return f'"{escaped}"'


def render_ahk(spec: dict, owner: str) -> str:
    lines = [
        "; Generated by nicegui-windows-console from hotstrings.json. Edit that file, not this one.",
        "#Requires AutoHotkey v2.0",
        "#SingleInstance Force",
        "",
        "PasteText(text) {",
        "    saved := ClipboardAll()",
        "    A_Clipboard := text",
        "    if ClipWait(1)",
        '        Send "^v"',
        "    Sleep 200  ; let the target app read the clipboard before restoring it",
        "    A_Clipboard := saved",
        "}",
        "",
        "SendClear(before := \"\") {",
        "    if before != \"\" {",
        "        Send before",
        "        Sleep 150",
        "    }",
        '    SendText "/clear"',
        "    Sleep 150  ; let the slash-command menu settle before Enter",
        '    Send "{Enter}"',
        "}",
        "",
        "; Prompts: paste on the trigger itself, no ending key needed.",
    ]
    for prompt in spec.get("prompts", []):
        lines.append(f":*X:{prompt['trigger']}::PasteText({_string(fill(prompt['text'], owner))})")
    lines += ["", "; Text: expands after an ending key, like a normal hotstring."]
    for item in spec.get("text", []):
        lines.append(f"::{item['trigger']}::{_send_escape(fill(item['text'], owner))}")
    lines += ["", "; Hotkeys"]
    by_app: dict[str | None, list[dict]] = {}
    for hotkey in spec.get("hotkeys", []):
        by_app.setdefault(hotkey.get("app"), []).append(hotkey)
    for app, hotkeys in by_app.items():
        if app:
            lines.append(f'#HotIf WinActive("ahk_exe {app}")')
        for hotkey in hotkeys:
            action = hotkey.get("action")
            if action == "hibernate":
                body = 'DllCall("PowrProf\\SetSuspendState", "Int", 1, "Int", 0, "Int", 0)'
            elif action == "clear":
                body = f"SendClear({_string(hotkey.get('before', ''))})"
            else:
                body = f"Send {_string(hotkey['send'])}"
            lines.append(f"{hotkey['keys']}::{body}  ; {hotkey['label']}")
        if app:
            lines.append("#HotIf")
    lines.append("")
    return "\n".join(lines)


def write_script(spec: dict, owner: str, script: Path) -> None:
    script.parent.mkdir(parents=True, exist_ok=True)
    # AutoHotkey reads UTF-8 reliably only with a byte-order mark.
    script.write_text(render_ahk(spec, owner), encoding="utf-8-sig")


def validate(exe: Path, script: Path) -> str | None:
    """None when the script loads cleanly, else AutoHotkey's error text."""
    result = subprocess.run(
        [str(exe), "/ErrorStdOut", "/Validate", str(script)],
        capture_output=True, text=True, timeout=20, creationflags=NO_WINDOW,
    )
    return None if result.returncode == 0 else (result.stderr or result.stdout or f"exit {result.returncode}").strip()


def running(script: Path) -> int | None:
    """PID of an AutoHotkey process running this script, if any."""
    match = procs.find(str(script.resolve()))
    return match.pid if match else None


def start(exe: Path, script: Path) -> None:
    """Run (or, through #SingleInstance Force, reload) the script."""
    subprocess.Popen([str(exe), str(script)], creationflags=NO_WINDOW, close_fds=True)
